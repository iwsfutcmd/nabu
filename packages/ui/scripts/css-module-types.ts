/**
 * Writes Foo.module.d.css.ts next to every Foo.module.css (TypeScript's
 * allowArbitraryExtensions lookup), declaring exactly the classes the file
 * defines. Misspelled class names then fail typecheck instead of silently
 * rendering `undefined`.
 *
 *   node scripts/css-module-types.ts           # write
 *   node scripts/css-module-types.ts --check   # exit 1 if any declaration is stale
 *   node scripts/css-module-types.ts --root ../../apps/web/src   # another package's sources
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const rootArg = process.argv.indexOf("--root");
const ROOT = rootArg >= 0 ? resolve(process.cwd(), process.argv[rootArg + 1] as string) : resolve(import.meta.dirname, "../src");
const check = process.argv.includes("--check");

const walk = (dir: string): string[] =>
  readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : e.name.endsWith(".module.css") ? [join(dir, e.name)] : [],
  );

const classesIn = (css: string): string[] => {
  const withoutComments = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const selectors = withoutComments.replace(/\{[^{}]*\}/g, "{}"); // drop declaration blocks
  return [...new Set([...selectors.matchAll(/\.(-?[_a-zA-Z][_a-zA-Z0-9-]*)/g)].map((m) => m[1] as string))].sort();
};

let stale = 0;
for (const file of walk(ROOT)) {
  const names = classesIn(readFileSync(file, "utf8"));
  const body = names.map((n) => `  readonly ${/^[_a-zA-Z][_a-zA-Z0-9]*$/.test(n) ? n : JSON.stringify(n)}: string;`).join("\n");
  const text = `// GENERATED by scripts/css-module-types.ts. Do not edit.\ndeclare const styles: {\n${body}\n};\nexport default styles;\n`;
  const out = file.replace(/\.module\.css$/, ".module.d.css.ts");
  if (check) {
    if (!existsSync(out) || readFileSync(out, "utf8") !== text) {
      console.error(`stale: ${relative(process.cwd(), out)}`);
      stale++;
    }
  } else {
    writeFileSync(out, text);
  }
}
if (stale > 0) {
  console.error("CSS module declarations are stale; run `pnpm codegen`.");
  process.exit(1);
}
