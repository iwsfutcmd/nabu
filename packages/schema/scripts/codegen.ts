/**
 * schemas/*.schema.json → src/generated/schema.ts
 *
 * json-schema-to-typescript does the translation; a post-pass then makes every
 * property, index signature, array and tuple readonly, so generated types match
 * gameplan §6.1. Run `pnpm codegen` from the repo root; CI fails if the output
 * differs from what is checked in.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { compile } from "json-schema-to-typescript";
import { bundle, readSchemas } from "./bundle.ts";
import { makeReadonly } from "./readonly.ts";

const OUT = resolve(import.meta.dirname, "../src/generated/schema.ts");

const BANNER = `/* eslint-disable */
// GENERATED by packages/schema/scripts/codegen.ts from /schemas.
// Do not edit by hand: change the JSON Schema and run \`pnpm codegen\`.
`;

const { anyOf: _roots, ...bundled } = bundle(readSchemas());
const defs = Object.keys(bundled["$defs"] as Record<string, unknown>);
// json-schema-to-typescript skips definitions reached only through a `tsType`
// override (RubySegment inside Token.ruby, MessageId in propertyNames), even with
// unreachableDefinitions. An index type that references every definition
// directly makes sure each one is declared.
const schema = {
  ...bundled,
  title: "NabuSchemaIndex",
  description: "Index of every Nabu schema type, so each is declared. Not a document type.",
  type: "object",
  properties: Object.fromEntries(defs.map((name) => [name, { $ref: `#/$defs/${name}` }])),
  required: defs,
  additionalProperties: false,
};
const generated = await compile(schema as Parameters<typeof compile>[0], "NabuSchemaIndex", {
  additionalProperties: false,
  unreachableDefinitions: true,
  ignoreMinAndMaxItems: true,
  bannerComment: "",
  style: { printWidth: 100, singleQuote: false, trailingComma: "all", bracketSpacing: true },
});
mkdirSync(resolve(OUT, ".."), { recursive: true });
writeFileSync(OUT, BANNER + makeReadonly(generated));
console.log(`wrote ${OUT}`);

