/**
 * Generates the UTS #39 data usernames need (gameplan §12.7) from Unicode's pinned security
 * files: the confusables map (for skeletons) and the characters whose Identifier_Status is
 * Allowed. Both are checked against pinned SHA-256 sums, so a regeneration can only reproduce
 * the committed files.
 *
 *   node scripts/generate-security.ts          # download, verify, write src/generated/*.json
 */
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const VERSION = "16.0.0";
const BASE = `https://www.unicode.org/Public/security/${VERSION}`;
const PINS: Readonly<Record<string, string>> = {
  "confusables.txt": "95bd0aad6dced5ebc63436f459c06ab21a8d107cd842fb57f5c3a1e91bca8611",
  "IdentifierStatus.txt": "c6108ca140e054b55a5b0378e7ebed8b1ef0e846251f6195361bc9af8ffc61b1",
};
const OUT = join(import.meta.dirname, "../src/generated");

const fetchPinned = async (name: string): Promise<string> => {
  const response = await fetch(`${BASE}/${name}`);
  if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`);
  const body = Buffer.from(await response.arrayBuffer());
  const sum = createHash("sha256").update(body).digest("hex");
  if (sum !== PINS[name]) throw new Error(`${name}: sha256 ${sum}, pinned ${PINS[name] ?? "?"}`);
  return body.toString("utf8");
};

const cp = (hex: string): string => String.fromCodePoint(Number.parseInt(hex, 16));

const lines = (text: string): string[][] =>
  text
    .split("\n")
    .map((l) => l.replace(/#.*/u, "").trim())
    .filter((l) => l !== "")
    .map((l) => l.split(";").map((f) => f.trim()));

const confusables = lines(await fetchPinned("confusables.txt"));
const map: Record<string, string> = {};
for (const [source, target] of confusables) {
  if (source === undefined || target === undefined) continue;
  map[cp(source)] = target.split(/\s+/u).map(cp).join("");
}

const allowed: [number, number][] = [];
for (const [range, status] of lines(await fetchPinned("IdentifierStatus.txt"))) {
  if (status !== "Allowed" || range === undefined) continue;
  const [a, b] = range.split("..");
  allowed.push([Number.parseInt(a ?? "", 16), Number.parseInt(b ?? a ?? "", 16)]);
}
allowed.sort((x, y) => x[0] - y[0]);

const header = (what: string) => ({
  $comment: `GENERATED by packages/i18n/scripts/generate-security.ts from Unicode ${VERSION} ${what}. Do not edit; run \`pnpm --filter @nabu/i18n generate:security\`.`,
  unicodeVersion: VERSION,
  license: "Unicode-3.0",
  source: `${BASE}/${what}`,
  sha256: PINS[what],
});

/** JSON with everything outside printable ASCII as \u escapes (UTF-16 code units, as JSON wants them). */
const asciiJson = (data: unknown): string => {
  const json = JSON.stringify(data, null, 1);
  let out = "";
  for (let i = 0; i < json.length; i += 1) {
    const u = json.charCodeAt(i);
    out += (u >= 0x20 && u <= 0x7e) || u === 0x0a ? json[i] : `\\u${u.toString(16).padStart(4, "0")}`;
  }
  return `${out}\n`;
};

const write = (file: string, data: unknown): void => writeFileSync(join(OUT, file), asciiJson(data));

write("confusables.json", { ...header("confusables.txt"), map });
write("identifier-allowed.json", { ...header("IdentifierStatus.txt"), ranges: allowed });
console.log(`confusables: ${Object.keys(map).length} entries; Allowed: ${allowed.length} ranges`);
